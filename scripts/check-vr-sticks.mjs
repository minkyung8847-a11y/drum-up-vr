import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createVirtualDrumsticks } from '../src/components/virtualDrumsticks.ts';

const parent = new THREE.Group();
const sticks = createVirtualDrumsticks(parent);
const leftSwing = sticks.grips.left.getObjectByName('left-stick-swing');
const rightSwing = sticks.grips.right.getObjectByName('right-stick-swing');
const rest = leftSwing.rotation.x;
parent.updateMatrixWorld(true);
const tipBefore = sticks.tips.left.getWorldPosition(new THREE.Vector3());
sticks.strike('left');
sticks.update(0.055);
parent.updateMatrixWorld(true);
assert(sticks.tips.left.getWorldPosition(new THREE.Vector3()).y < tipBefore.y - 0.08, 'Left tip moves down');
assert.equal(rightSwing.rotation.x, rest, 'Left strike does not move right stick');
sticks.update(0.03);
const partial = leftSwing.rotation.x;
sticks.strike('left');
sticks.update(0);
assert(Math.abs(leftSwing.rotation.x - partial) < 1e-12, 'Rapid retrigger does not snap');
sticks.strike('right');
sticks.update(0.055);
assert(rightSwing.rotation.x < rest, 'Right stick animates independently');
sticks.update(0.3);
assert.equal(leftSwing.rotation.x, rest);
assert.equal(rightSwing.rotation.x, rest);
assert.equal(parent.children.length, 2);
assert.notEqual(sticks.grips.left, sticks.grips.right);
const leftGrip = sticks.grips.left.matrix.clone();
const target = new THREE.Vector3(-0.5, -0.8, -1.1);
for (let hit = 0; hit < 40; hit++) {
  const expected = hit % 2 === 0 ? 'left' : 'right';
  assert.equal(sticks.strikeAlternating(target), expected);
  sticks.update(0.03);
  const active = expected === 'left' ? leftSwing : rightSwing;
  const other = expected === 'left' ? rightSwing : leftSwing;
  assert.equal(other.rotation.x, rest, 'Inactive stick remains at rest during rapid alternating hits');
  assert(active.quaternion.angleTo(new THREE.Quaternion().setFromEuler(new THREE.Euler(rest, 0, 0))) > 0.01);
}
sticks.update(0.3);
assert.equal(leftSwing.rotation.x, rest);
assert.equal(rightSwing.rotation.x, rest);
assert.deepEqual(sticks.grips.left.matrix.toArray(), leftGrip.toArray(), 'Striking never changes the grip transform');
const tracked = createVirtualDrumsticks(new THREE.Group(), false);
assert.equal(tracked.strikeAlternating(target), null, 'Tracked VR sticks never auto-alternate');
tracked.dispose();
const raisedParent = new THREE.Group();
const raised = createVirtualDrumsticks(raisedParent);
raised.strikeAlternating(new THREE.Vector3(0.8, 0.4, -1.5));
raised.update(0.018);
raisedParent.updateMatrixWorld(true);
const preparedTip = raised.tips.left.getWorldPosition(new THREE.Vector3());
raised.update(0.037);
raisedParent.updateMatrixWorld(true);
assert(raised.tips.left.getWorldPosition(new THREE.Vector3()).y < preparedTip.y - 0.01, 'Raised cymbal strike has a downward impact phase');
raised.dispose();
console.log('PASS: independent sticks; targeted downward strokes; 40 rapid L/R alternating hits; only active stick moves; return to rest; tracked sticks excluded.');
